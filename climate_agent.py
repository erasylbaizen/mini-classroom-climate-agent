# Mini Classroom Climate Agent (Topic #18)
# Integrates: 1) Hill Climbing, 2) Bayesian Inference, 3) Markov Decision Process (MDP)


def hill_climbing(setpoints, scores, start_idx=0):
    """Algorithm 1: Hill Climbing to find the best temperature setpoint."""
    current = start_idx
    trace = [f"{setpoints[current]}°C (score={scores[current]})"]

    while True:
        neighbors = []
        if current > 0:
            neighbors.append(current - 1)
        if current < len(scores) - 1:
            neighbors.append(current + 1)

        best = current
        for n in neighbors:
            if scores[n] > scores[best]:
                best = n

        if best == current:
            break
        current = best
        trace.append(f"{setpoints[current]}°C (score={scores[current]})")

    return setpoints[current], scores[current], trace


def bayesian_inference(prior_hot, p_obs_given_hot, p_obs_given_normal):
    """Algorithm 2: Bayesian update for P(Too Hot | Sensor Observation)."""
    score_hot = prior_hot * p_obs_given_hot
    score_normal = (1.0 - prior_hot) * p_obs_given_normal
    total = score_hot + score_normal

    if total == 0:
        raise ValueError("Observation has zero total probability.")

    posterior_hot = score_hot / total
    return posterior_hot, score_hot, score_normal


def mdp_choose_action(current_state, transitions, rewards):
    """Algorithm 3: One-step expected reward calculation in a 2-state MDP."""
    expected_values = {}
    for action, outcomes in transitions[current_state].items():
        ev = 0.0
        for next_state, prob in outcomes.items():
            ev += prob * rewards[current_state][action][next_state]
        expected_values[action] = ev

    best_action = max(expected_values, key=expected_values.get)
    return best_action, expected_values


def run_simulation(scenario_name, prior_hot, sensor_reading, start_idx=0):
    print("\n" + "=" * 65)
    print(f"SCENARIO: {scenario_name}")
    print("=" * 65)

    # --- ASSUMPTIONS ---
    setpoints = [18, 20, 22, 24, 26]  # Celsius
    comfort_scores = [45, 72, 95, 80, 50]  # Predefined utility scores

    # Sensor model: P(Reading | State)
    sensor_model = {
        "ALERT": (0.85, 0.15),  # P(ALERT | Too Hot)=0.85, P(ALERT | Normal)=0.15
        "NORMAL": (0.15, 0.85),  # P(NORMAL | Too Hot)=0.15, P(NORMAL | Normal)=0.85
    }

    # MDP model: 2 states ('Too Hot', 'Normal'), 2 actions ('Cool', 'Wait')
    transitions = {
        "Too Hot": {
            "Cool": {"Normal": 0.90, "Too Hot": 0.10},
            "Wait": {"Normal": 0.20, "Too Hot": 0.80},
        },
        "Normal": {
            "Cool": {"Normal": 0.95, "Too Hot": 0.05},
            "Wait": {"Normal": 0.85, "Too Hot": 0.15},
        },
    }
    rewards = {
        "Too Hot": {
            "Cool": {"Normal": 10.0, "Too Hot": -2.0},
            "Wait": {"Normal": 5.0, "Too Hot": -10.0},
        },
        "Normal": {
            "Cool": {"Normal": 2.0, "Too Hot": -5.0},  # Unnecessary energy cost
            "Wait": {"Normal": 8.0, "Too Hot": -3.0},
        },
    }

    # 1. HILL CLIMBING
    best_temp, best_score, trace = hill_climbing(setpoints, comfort_scores, start_idx)
    print("\n[1] HILL CLIMBING (Optimal Setpoint Search)")
    print(f"  Input:       Setpoints={setpoints}, Scores={comfort_scores}, Start={setpoints[start_idx]}°C")
    print(f"  Steps:       {' -> '.join(trace)}")
    print(f"  Output:      Best Setpoint = {best_temp}°C (Score = {best_score})")
    print("  Explanation: Hill climbing greedily moves to higher-scoring neighbor temperatures until reaching the comfort peak.")

    # 2. BAYESIAN INFERENCE
    p_obs_hot, p_obs_norm = sensor_model[sensor_reading]
    post_hot, s_hot, s_norm = bayesian_inference(prior_hot, p_obs_hot, p_obs_norm)
    print("\n[2] BAYESIAN INFERENCE (Heat State Estimation)")
    print(f"  Input:       Prior P(Too Hot)={prior_hot:.2f}, Sensor='{sensor_reading}', P(Obs|Hot)={p_obs_hot}, P(Obs|Normal)={p_obs_norm}")
    print(f"  Steps:       Score(Hot)={s_hot:.4f}, Score(Normal)={s_norm:.4f}, Sum={s_hot + s_norm:.4f}")
    print(f"  Output:      Posterior P(Too Hot | {sensor_reading}) = {post_hot:.4f} ({post_hot * 100:.2f}%)")
    print("  Explanation: Bayes' rule updates our prior belief about classroom heat by weighing the noisy sensor reading against false-alarm rates.")

    # 3. MDP DECISION MAKING
    inferred_state = "Too Hot" if post_hot >= 0.50 else "Normal"
    best_action, ev_dict = mdp_choose_action(inferred_state, transitions, rewards)
    print("\n[3] MARKOV DECISION PROCESS (Action Selection)")
    print(f"  Input:       Inferred State='{inferred_state}' (from Bayes), Actions=['Cool', 'Wait']")
    print(f"  Steps:       E[Cool] = {ev_dict['Cool']:+.2f}, E[Wait] = {ev_dict['Wait']:+.2f}")
    print(f"  Output:      Recommended Action = '{best_action.upper()}' (Target: {best_temp}°C)")
    print("  Explanation: The MDP selects the action with the highest one-step expected reward by balancing thermal comfort against energy cost.")
    print("=" * 65)


def main():
    while True:
        print("\n=== Mini Classroom Climate Agent ===")
        print("1. Test Case 1: High-Temp Sensor Alert (Prior = 0.30, Reading = ALERT)")
        print("2. Test Case 2: Normal Sensor Reading (Prior = 0.30, Reading = NORMAL)")
        print("3. Custom Input (Enter your own prior and sensor reading)")
        print("0. Exit")

        choice = input("Select an option (0-3): ").strip()
        if choice == "1":
            run_simulation("Test Case 1 - Sensor Alert", prior_hot=0.30, sensor_reading="ALERT", start_idx=0)
        elif choice == "2":
            run_simulation("Test Case 2 - Normal Reading", prior_hot=0.30, sensor_reading="NORMAL", start_idx=4)
        elif choice == "3":
            try:
                p = float(input("Enter prior probability of Too Hot (0.0 to 1.0, e.g. 0.4): ").strip())
                if not 0.0 <= p <= 1.0:
                    raise ValueError
                r = input("Enter sensor reading (ALERT or NORMAL): ").strip().upper()
                if r not in ("ALERT", "NORMAL"):
                    raise ValueError
                run_simulation("Custom User Scenario", prior_hot=p, sensor_reading=r, start_idx=0)
            except ValueError:
                print("Invalid input. Please enter a probability between 0 and 1, and ALERT or NORMAL.")
        elif choice == "0":
            print("Exiting program.")
            break
        else:
            print("Invalid option. Please choose 0, 1, 2, or 3.")


if __name__ == "__main__":
    main()